class details:
    language = "py"
    salary = "2000000"

naveed = details()
naveed.name = "Naveed"
print(naveed.name, naveed.salary, naveed.language)

haseeb = details()
haseeb.name = "Haseeb"
print(haseeb.name, haseeb.language, haseeb.salary)


# Here name is the object attribute and language and salary are class attributes as they directly belong to class